use std::env;
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

fn collect_files_recursive(base: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    println!("cargo:rerun-if-changed={}", dir.display());
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };

    let mut sorted_entries: Vec<_> = entries.flatten().collect();
    sorted_entries.sort_by_key(|e| e.file_name());

    for entry in sorted_entries {
        let path = entry.path();
        if path.is_dir() {
            collect_files_recursive(base, &path, out);
        } else if path.is_file() {
            println!("cargo:rerun-if-changed={}", path.display());
            if let Ok(rel) = path.strip_prefix(base) {
                let rel_slash = rel
                    .components()
                    .map(|c| c.as_os_str().to_string_lossy().into_owned())
                    .collect::<Vec<_>>()
                    .join("/");
                out.push((rel_slash, path));
            }
        }
    }
}

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let ui_dist = manifest_dir.join("ui").join("dist");
    println!("cargo:rerun-if-changed={}", ui_dist.display());

    let mut files = Vec::new();
    if ui_dist.is_dir() {
        collect_files_recursive(&ui_dist, &ui_dist, &mut files);
    }
    files.sort_by(|a, b| a.0.cmp(&b.0));

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let dest_path = out_dir.join("embedded_ui.rs");
    let mut f = fs::File::create(&dest_path).expect("Failed creating embedded_ui.rs");

    writeln!(
        f,
        "// Auto-generated by build.rs — embeds agent/crates/swm-center/ui/dist into swm-center"
    )
    .unwrap();
    writeln!(f, "pub static EMBEDDED_UI_ASSETS: &[(&str, &[u8])] = &[").unwrap();
    for (rel_path, abs_path) in &files {
        let abs_str = abs_path.to_string_lossy();
        writeln!(f, "    ({:?}, include_bytes!({:?})),", rel_path, abs_str).unwrap();
    }
    writeln!(f, "];").unwrap();
}
